"""Gera arquivos Office EM BRANCO (docx/xlsx/pptx) sem dependências externas.

Os formatos OOXML são pacotes ZIP com partes XML. Aqui montamos o conjunto
mínimo de partes que o Word/Excel/PowerPoint (e o OnlyOffice) abrem como um
documento novo e vazio, pronto para editar. Usado pela action `create_blank`
do painel de Observações do roteiro."""
import io
import zipfile

# kind (OnlyOffice) -> extensão do arquivo
KIND_EXT = {'word': 'docx', 'cell': 'xlsx', 'slide': 'pptx'}


def _zip(parts):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED) as z:
        for path, content in parts.items():
            z.writestr(path, content.strip() if isinstance(content, str) else content)
    return buf.getvalue()


