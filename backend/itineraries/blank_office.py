def blank_file(kind):
    """Bytes de um arquivo Office em branco para o kind ('word'|'cell'|'slide')."""
    if kind == 'word':  return _docx()
    if kind == 'cell':  return _xlsx()
    if kind == 'slide': return _pptx()
    raise ValueError(f'kind inválido: {kind}')
